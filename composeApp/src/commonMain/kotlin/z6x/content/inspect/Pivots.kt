            4. 写内容时凭印象补了一行 `java -version` 的输出 → 实际跑一遍才发现少了一行 → **所有实测输出必须真跑**，`--try-read` 会自动对比。
            5. 把权限实验命令标成了"只读" → `--check` 指出它们其实是修改操作（只是预期被拒）→ 按真实风险标注。
