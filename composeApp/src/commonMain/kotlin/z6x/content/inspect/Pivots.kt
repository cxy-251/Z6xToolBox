        text("""
            1. 型号：`ro.product.model` 只写了 XGIMI TV → **不盯着一个属性**，getprop 全量搜 → 型号藏在蓝牙名里。芯片也是平台代号、产品名、/proc/cpuinfo 交叉验证才确定。（案例：查出真实型号和芯片）
